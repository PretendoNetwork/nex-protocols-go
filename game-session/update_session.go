// Package protocol implements the GameSession protocol
package protocol

import (
	"fmt"

	nex "github.com/PretendoNetwork/nex-go/v2"
	game_session_types "github.com/PretendoNetwork/nex-protocols-go/v2/game-session/types"
	"github.com/PretendoNetwork/nex-protocols-go/v2/globals"
)

func (protocol *Protocol) handleUpdateSession(packet nex.PacketInterface) {
	if protocol.UpdateSession == nil {
		err := nex.NewError(nex.ResultCodes.Core.NotImplemented, "GameSession::UpdateSession not implemented")

		globals.Logger.Warning(err.Message)
		globals.RespondError(packet, ProtocolID, err)

		return
	}

	request := packet.RMCMessage()
	callID := request.CallID
	parameters := request.Parameters
	endpoint := packet.Sender().Endpoint()
	parametersStream := nex.NewByteStreamIn(parameters, endpoint.LibraryVersions(), endpoint.ByteStreamSettings())

	var gameSessionUpdate game_session_types.GameSessionUpdate

	err := gameSessionUpdate.ExtractFrom(parametersStream)
	if err != nil {
		_, rmcError := protocol.UpdateSession(fmt.Errorf("failed to read gameSessionUpdate from parameters. %s", err.Error()), packet, callID, gameSessionUpdate)
		if rmcError != nil {
			globals.RespondError(packet, ProtocolID, rmcError)
		}

		return
	}

	rmcMessage, rmcError := protocol.UpdateSession(nil, packet, callID, gameSessionUpdate)
	if rmcError != nil {
		globals.RespondError(packet, ProtocolID, rmcError)
		return
	}

	globals.Respond(packet, rmcMessage)
}
